'use strict';
// Applies tools/values.json (from `node tools/sim.js calibrate`) to js/data.js:
//  1. writes the measured AI strength values (TUNED_V block)
//  2. nudges the gold cost of outlier creatures toward the median value-per-gold
const fs = require('fs'), path = require('path');
const file = path.join(__dirname, '..', 'js', 'data.js');
const vals = JSON.parse(fs.readFileSync(path.join(__dirname, 'values.json'), 'utf8'));
let src = fs.readFileSync(file, 'utf8');

const TARGET = 1.4;
const round = (g) => (g < 100 ? Math.round(g / 5) * 5 : g < 1000 ? Math.round(g / 10) * 10 : Math.round(g / 50) * 50);
const report = [];
src = src.replace(/(\[\s*'([^']*)', '[^']*', '[^']*', (?:\d+, ){8})(\d+)/g, (m, head, name, gold) => {
  // find the creature id for this entry by scanning the faction blocks in order
  return m;
});

// map entries to ids by walking FD faction blocks in source order
const lines = src.split('\n');
let fac = null, idx = 0;
for (let i = 0; i < lines.length; i++) {
  const f = lines[i].match(/^  (\w+): \[\s*$/) || lines[i].match(/^  (\w+): \[$/);
  const fm = lines[i].match(/^  (castle|rampart|tower|inferno|necropolis|dungeon|stronghold|fortress|conflux): \[/);
  if (fm) { fac = fm[1]; idx = 0; }
  const re = /(\[\s*'[^']*', '[^']*', '[^']*', (?:\d+, ){8})(\d+)/;
  const m = fac && lines[i].match(re);
  if (m && /^\s+(\[|  \[)/.test(lines[i]) || (m && fac)) {
    idx++;
    const id = fac + idx, gold = +m[2], v = vals[id] && vals[id][0];
    if (v) {
      const r = v / gold;
      if (Math.abs(r / TARGET - 1) > 0.2) {
        const ng = round(gold * Math.sqrt(r / TARGET));
        if (ng !== gold) { lines[i] = lines[i].replace(re, `$1${ng}`); report.push(`${id}: gold ${gold} -> ${ng} (value/gold ${r.toFixed(2)})`); }
      }
    }
    if (idx === 7) fac = null;
  }
}
src = lines.join('\n');

const block = `// BEGIN TUNED_V (generated by tools/apply_calibration.js)\nconst TUNED_V = ${JSON.stringify(vals)};\nObject.keys(TUNED_V).forEach(id => { const [v1, v5] = TUNED_V[id]; for (let L = 1; L <= MAX_LV; L++) C[lineType(id, L)].v = Math.round(v1 * Math.pow(v5 / v1, (L - 1) / 4)); });\n// END TUNED_V\n`;
if (src.includes('// BEGIN TUNED_V')) src = src.replace(/\/\/ BEGIN TUNED_V[\s\S]*?\/\/ END TUNED_V\n/, block);
else src = src.replace('// hero roster: id -> definition', block + '\n// hero roster: id -> definition');
fs.writeFileSync(file, src);
console.log(report.join('\n') || 'no cost changes');
